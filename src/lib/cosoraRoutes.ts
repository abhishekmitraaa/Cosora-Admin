/** True when `path` (no query or hash) matches one of the app's routes; ":param" matches one segment. */
export function isKnownCosoraRoute(path: string): boolean {
  const clean = path.split(/[?#]/)[0].replace(/\/+$/, "") || "/";
  return COSORA_ROUTES.some((r) => {
    const pattern = r
      .split("/")
      .map((seg) => (seg.startsWith(":") ? "[^/]+" : seg.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")))
      .join("/");
    return new RegExp(`^${pattern}$`).test(clean);
  });
}
